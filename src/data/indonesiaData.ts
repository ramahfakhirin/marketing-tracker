export const formatCityName = (city?: string, province?: string): string => {
  if (!city || !city.trim()) return '';
  let c = city.trim().toUpperCase();

  // Handle common abbreviations
  if (c.startsWith('KAB ')) {
    c = 'KABUPATEN ' + c.substring(4).trim();
  } else if (c.startsWith('KT ')) {
    c = 'KOTA ' + c.substring(3).trim();
  }

  // If already prefixed with KOTA or KABUPATEN, preserve exact designation
  if (c.startsWith('KOTA ') || c.startsWith('KABUPATEN ')) {
    return c;
  }

  // If missing prefix, match against official province or national data
  const upperProv = province?.toUpperCase().trim();
  if (upperProv && INDONESIAN_PROVINCES_DATA[upperProv]) {
    const list = INDONESIAN_PROVINCES_DATA[upperProv];
    const matchKota = list.find(item => item === 'KOTA ' + c);
    const matchKab = list.find(item => item === 'KABUPATEN ' + c);

    if (matchKota && !matchKab) return 'KOTA ' + c;
    if (matchKab && !matchKota) return 'KABUPATEN ' + c;
    if (matchKota && matchKab) return 'KOTA ' + c; // Default if plain name passed
  }

  // Search globally if province not specified
  let foundKota = false;
  let foundKab = false;

  for (const provList of Object.values(INDONESIAN_PROVINCES_DATA)) {
    if (provList.includes('KOTA ' + c)) foundKota = true;
    if (provList.includes('KABUPATEN ' + c)) foundKab = true;
  }

  if (foundKota && !foundKab) return 'KOTA ' + c;
  if (foundKab && !foundKota) return 'KABUPATEN ' + c;

  // Fallback if unrecognized: keep original
  return c;
};

export const isSameCity = (cityA?: string, cityB?: string, province?: string): boolean => {
  if (!cityA || !cityB) return false;
  const formattedA = formatCityName(cityA, province);
  const formattedB = formatCityName(cityB, province);
  return formattedA === formattedB;
};
